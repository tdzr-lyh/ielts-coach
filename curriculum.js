const resource = (subject, book, test, unit, from, to) => ({
  book, test, unit, from, to,
  sourceUrl: `https://engnovate.com/ielts-${subject}-tests/cambridge-ielts-${book}-academic-${subject}-test-${test}/`,
  verified: true,
});
const R = (book, test, unit, from, to) => resource('reading', book, test, unit, from, to);
const L = (book, test, unit, from, to) => resource('listening', book, test, unit, from, to);
const RF = (book, test) => R(book, test, null, 1, 40);
const LF = (book, test) => L(book, test, null, 1, 40);
const task = (title, kind, methodId, resources = [], sourceDay) => ({
  title, kind, methodId, resources, minutes: 90,
  ...(sourceDay === undefined ? {} : { sourceDay }),
});
// 四个时间块之和等于听力总时长。精听片段与短句听写在 reviewMinutes 内完成，
// spellingMinutes 用于当日易错词/数字，recallMinutes 用于已经做过的内容，不另加新题。
const listeningTask = (title, kind, methodId, resources, minutes, listeningPlan, sourceDay) => ({
  ...task(title, kind, methodId, resources, sourceDay), minutes, listeningPlan,
});
const listeningPlan = (newQuestions, firstPassMinutes, reviewMinutes, spellingMinutes, recallMinutes,
  segments, segmentSeconds, dictationSentences, instruction) => ({
  newQuestions, firstPassMinutes, reviewMinutes, spellingMinutes, recallMinutes,
  segments, segmentSeconds, dictationSentences, instruction,
});
const day = (number, title, reading, listening) => ({
  day: number,
  phase: PHASES.find(phase => number >= phase.from && number <= phase.to).title,
  title, reading, listening,
});

